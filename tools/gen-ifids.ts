/** Why: pack names are stable across revisions while component ids are not, so the hand-maintained list carries names and the generator resolves ids per revision; usage in docs/how-to/build-and-data.md. */
import { resolveOut } from './lib/genout.js';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';

const CONTENT = process.env.CONTENT_DIR ?? join(homedir(), 'code', 'rs2b2t-content');
const LIST = 'tools/ifids.list';
const OUT = resolveOut('src/bot/data/ifIds.ts');

/** `tradeconfirm:inv1` → `TRADECONFIRM_INV1`; the constant is derived from the pack name. */
function constantOf(packName: string): string {
    return packName.toUpperCase().replace(/[^A-Z0-9]+/g, '_');
}

function packIds(): Map<string, number> {
    const out = new Map<string, number>();
    for (const raw of readFileSync(join(CONTENT, 'pack', 'interface.pack'), 'utf8').split('\n')) {
        const m = /^(\d+)=(\S+)$/.exec(raw.trim());
        if (m) {
            out.set(m[2], Number(m[1]));
        }
    }
    return out;
}

function listNames(): string[] {
    const names: string[] = [];
    for (const raw of readFileSync(LIST, 'utf8').split('\n')) {
        const line = raw.trim();
        if (line.length === 0 || line.startsWith('#')) {
            continue;
        }
        names.push(line);
    }
    return names;
}

function generate(): string {
    const ids = packIds();
    const rows: { constant: string; name: string; id: number }[] = [];
    for (const name of listNames()) {
        const id = ids.get(name);
        if (id === undefined) {
            throw new Error(`pack name '${name}' is not in ${join(CONTENT, 'pack', 'interface.pack')} (check tools/ifids.list and the content checkout)`);
        }
        const constant = constantOf(name);
        if (rows.some(r => r.constant === constant)) {
            throw new Error(`pack names '${name}' collide on constant ${constant}`);
        }
        rows.push({ constant, name, id });
    }
    console.log(`ifids=${rows.length}`);

    const idLines = rows.map(r => `    ${r.constant}: ${r.id},`);
    return [
        '/* eslint-disable */',
        '// GENERATED by tools/gen-ifids.ts from the interface.pack named by tools/ifids.list, do not edit.',
        '// Regenerate: bun tools/gen-ifids.ts   (drift gate: bun tools/gen-ifids.ts --check)',
        '',
        '/** Component ids for the pack names in tools/ifids.list, resolved per revision. */',
        'export const IF_IDS = {',
        idLines.join('\n'),
        '} as const;',
        ''
    ].join('\n');
}

const fresh = generate();
if (process.argv.includes('--check')) {
    let current = '';
    try {
        current = readFileSync(OUT, 'utf8');
    } catch {
        // Missing output is stale.
    }
    if (current !== fresh) {
        console.error(`STALE: ${OUT} does not match the interface pack — run: bun tools/gen-ifids.ts`);
        process.exit(1);
    }
    console.log(`ok: ${OUT} matches the interface pack`);
} else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, fresh);
    console.log(`wrote ${OUT}`);
}
